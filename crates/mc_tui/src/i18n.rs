#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn language_endonyms_stable() {
        assert_eq!(Lang::En.native_label(), "English");
        assert_eq!(Lang::Uk.native_label(), "Українська");
        assert_eq!(Lang::Ru.native_label(), "Русский");
        assert_eq!(Lang::from_native_label("Українська"), Some(Lang::Uk));
    }

    #[test]
    fn en_fallback_returns_key_for_unknown() {
        assert_eq!(en("does.not.exist"), "does.not.exist");
    }

    #[test]
    fn uk_and_ru_translate_core_keys() {
        for key in [
            "nav.instances",
            "settings.language",
            "btn.launch",
            "hint.save",
        ] {
            assert_ne!(
                tr_string(Lang::Uk, key),
                tr_string(Lang::En, key),
                "uk missing {key}"
            );
            assert_ne!(
                tr_string(Lang::Ru, key),
                tr_string(Lang::En, key),
                "ru missing {key}"
            );
        }
    }

    #[test]
    fn missing_uk_key_falls_back_to_en() {
        assert_eq!(tr_string(Lang::Uk, "nav.instances"), "Збірки");
        assert_eq!(tr_string(Lang::En, "nav.instances"), "Instances");
    }

    #[test]
    fn cycle_wraps() {
        assert_eq!(Lang::En.cycle(true), Lang::Uk);
        assert_eq!(Lang::Ru.cycle(true), Lang::En);
        assert_eq!(Lang::En.cycle(false), Lang::Ru);
    }
}
