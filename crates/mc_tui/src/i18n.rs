//! UI localization: English, Ukrainian, Russian.
//!
//! Keys are stable dotted identifiers (`nav.instances`, `btn.launch`, …).
//! Missing translations fall back to English, then to the key itself.

use serde::{Deserialize, Serialize};

/// UI language stored in `settings.json`.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Lang {
    #[default]
    En,
    Uk,
    Ru,
}

impl Lang {
    pub const ALL: &'static [Lang] = &[Lang::En, Lang::Uk, Lang::Ru];

    /// Native endonym shown in the language picker (never translated).
    pub fn native_label(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Uk => "Українська",
            Lang::Ru => "Русский",
        }
    }

    pub fn from_native_label(s: &str) -> Option<Lang> {
        Lang::ALL.iter().copied().find(|l| l.native_label() == s)
    }

    pub fn cycle(self, forward: bool) -> Lang {
        let all = Lang::ALL;
        let i = all.iter().position(|l| *l == self).unwrap_or(0);
        all[if forward {
            (i + 1) % all.len()
        } else {
            (i + all.len() - 1) % all.len()
        }]
    }
}

/// Translate `key` for `lang`. English is the fallback chain root.
///
/// Known keys return a `&'static str`; unknown keys are returned as a
/// temporary `Cow::Owned` so the key itself remains visible for debugging.
pub fn tr(lang: Lang, key: &str) -> std::borrow::Cow<'static, str> {
    match lang {
        Lang::En => en(key),
        Lang::Uk => uk(key)
            .map(std::borrow::Cow::Borrowed)
            .unwrap_or_else(|| en(key)),
        Lang::Ru => ru(key)
            .map(std::borrow::Cow::Borrowed)
            .unwrap_or_else(|| en(key)),
    }
}

/// Convenience: owned string form of [`tr`].
pub fn tr_string(lang: Lang, key: &str) -> String {
    tr(lang, key).into_owned()
}

/// Known English string for `key`, or the key itself if unknown.
/// Used when a `&'static str` is required and the key is not in the table.
pub(crate) fn en_static(key: &str) -> &'static str {
    // All English entries are `&'static str`; re-match to get one.
    // For unknown keys we cannot return `key` (not static), so return a
    // visible placeholder that still identifies the missing key in logs.
    match en(key) {
        std::borrow::Cow::Borrowed(s) => s,
        std::borrow::Cow::Owned(_) => "«?»",
    }
}

